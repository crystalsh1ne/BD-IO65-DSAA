#include <stdio.h>

#define M 8
#define N 7

int
main ()
{
  double X;
  printf ("Enter a number (in 0.00 format):\n");
  scanf ("%.2lf", &X);
  int L = 0;
  int R = M - 1;
  int k = 0;

  double arr[M][N] = {
                    {9.50,   9.50,  12.00,  5.50,  15.75,  6.90,  10.10},
		    {9.50,   7.10,  10.50,  5.50,  11.20,  6.90,  8.80},
		    {5.25,   7.10,  8.20,   5.50,  9.80,   5.00,  8.80},
		    {5.25,   7.10,  6.40,   2.20,  9.80,   3.33,  6.15},
		    {5.25,   4.00,  6.40,   2.20,  7.30,   3.33,  4.40},
		    {5.25,   2.75,  3.10,  -1.10,  4.60,   3.33,  4.40},
		    {1.10,   2.75,  1.80,  -1.10,  2.10,   1.00,  0.75},
		    {1.10,  -0.50,  0.00,  -4.80,  2.10,   -2.40, 0.75}
  }; // array was generated by AI for convenience and slightly changed by me

  for (int j = 0; j < N; j++)
    {
      while (L != R)
	{
	  k = (L+R)/2;
	  if (arr[k][j] <= X)
	    {
	      R = k;
	    }
	  else if (arr[k][j] > X)
	    {
	      L = k+1;
	    }
	}
      if (arr[L][j] == X)
	{
	  printf ("A match has been found! Element %.2lf is at coordinates [%d][%d].\n", arr[L][j], L, j);
	}
      L = 0;
      R = 7;
    }
  return 0;
}
