#include <stdio.h>

#define M 8
#define N 9


void
sort(int arr[M][N])
{
  int j;
  int t;
  for (int x = 0; x < M; x++)
    {
      for (int i = 1; i < N; i++)
        {
          t = arr[x][i];
          j = i;
          while (j > 0 && arr[x][j-1] < t)
            {
              arr[x][j] = arr[x][j-1];
              j = j-1;
            }
          arr[x][j] = t;
        }
    }
}

void
printarr(int arr[M][N])
{
  for (int i = 0; i < M; i++)
    {
      for (int j = 0; j < N; j++)
        {
          printf ("%d ", arr[i][j]); 
        }
      printf ("\n");
    }
}

void
dosort(int arr[M][N])
{
  sort(arr);
  printarr(arr);
}

